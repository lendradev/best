import { describe, expect, test } from 'bun:test';
import { Database } from '../src/orm/client.ts';
import {
  getDialect,
  mariadbDialect,
  mysqlDialect,
  postgresDialect,
  sqliteDialect,
} from '../src/orm/dialect.ts';
import { inferAdapter, SqliteDriver } from '../src/orm/driver.ts';
import { createTableSql, generateMigration } from '../src/orm/migrate.ts';
import {
  countNumberedPlaceholders,
  countPlaceholders,
  numberPlaceholders,
  renderSql,
} from '../src/orm/render.ts';
import { boolean, id, integer, table, text } from '../src/orm/schema.ts';

const users = table('users', [
  id(),
  text('email', { notNull: true, unique: true }),
  text('name', { notNull: true }),
  integer('age'),
  boolean('active'),
]);

describe('dialects', () => {
  test('getDialect returns the dialect for every name', () => {
    expect(getDialect('sqlite').name).toBe('sqlite');
    expect(getDialect('postgres').name).toBe('postgres');
    expect(getDialect('mysql').name).toBe('mysql');
    expect(getDialect('mariadb').name).toBe('mariadb');
  });

  test('getDialect rejects an unknown name', () => {
    // @ts-expect-error the name is not part of DialectName
    expect(() => getDialect('oracle')).toThrow('Unknown dialect');
  });

  test('placeholders follow the backend syntax', () => {
    expect(sqliteDialect.placeholder(1)).toBe('?');
    expect(mysqlDialect.placeholder(1)).toBe('?');
    expect(mariadbDialect.placeholder(1)).toBe('?');
    expect(postgresDialect.placeholder(1)).toBe('$1');
    expect(postgresDialect.placeholder(3)).toBe('$3');
  });

  test('identifiers are quoted per backend', () => {
    expect(sqliteDialect.quote('userId')).toBe('"userId"');
    expect(postgresDialect.quote('userId')).toBe('"userId"');
    expect(mysqlDialect.quote('userId')).toBe('`userId`');
  });

  test('a quote inside an identifier is escaped', () => {
    expect(sqliteDialect.quote('a"b')).toBe('"a""b"');
    expect(postgresDialect.quote('a"b')).toBe('"a""b"');
    expect(mysqlDialect.quote('a`b')).toBe('`a``b`');
  });

  test('RETURNING support differs per backend', () => {
    expect(sqliteDialect.supportsReturning).toBe(true);
    expect(postgresDialect.supportsReturning).toBe(true);
    expect(mariadbDialect.supportsReturning).toBe(true);
    expect(mysqlDialect.supportsReturning).toBe(false);
    expect(mysqlDialect.supportsReturningOnUpdate).toBe(false);
  });

  test('only the backends that count matched rows report them', () => {
    expect(sqliteDialect.countsMatchedRows).toBe(true);
    expect(postgresDialect.countsMatchedRows).toBe(true);
    expect(mysqlDialect.countsMatchedRows).toBe(false);
    expect(mariadbDialect.countsMatchedRows).toBe(false);
  });

  test('case-insensitive matching uses the backend expression', () => {
    expect(postgresDialect.ilike('"name"')).toBe('"name" ILIKE ?');
    expect(sqliteDialect.ilike('"name"')).toBe('LOWER("name") LIKE LOWER(?)');
    expect(mysqlDialect.ilike('`name`')).toBe('LOWER(`name`) LIKE LOWER(?)');
  });

  test('booleans are stored as the backend stores them', () => {
    expect(sqliteDialect.toStorage(true)).toBe(1);
    expect(mysqlDialect.toStorage(true)).toBe(1);
    expect(mariadbDialect.toStorage(false)).toBe(0);
    expect(postgresDialect.toStorage(true)).toBe(true);
  });

  test('column types follow the backend', () => {
    expect(sqliteDialect.columnType('boolean')).toBe('BOOLEAN');
    expect(postgresDialect.columnType('boolean')).toBe('BOOLEAN');
    expect(mysqlDialect.columnType('boolean')).toBe('TINYINT(1)');
    expect(postgresDialect.columnType('json')).toBe('JSONB');
    expect(mysqlDialect.columnType('json')).toBe('JSON');
  });

  test('boolean defaults use the backend spelling', () => {
    expect(sqliteDialect.defaultValue(true)).toBe('1');
    expect(mysqlDialect.defaultValue(true)).toBe('1');
    expect(postgresDialect.defaultValue(true)).toBe('TRUE');
    expect(postgresDialect.defaultValue(false)).toBe('FALSE');
  });

  test('the SQLite DDL matches the committed schema', () => {
    const sql = createTableSql(users, sqliteDialect);
    expect(sql).toContain('CREATE TABLE IF NOT EXISTS "users"');
    expect(sql).toContain('"email" TEXT NOT NULL UNIQUE');
    expect(sql).toContain('"id" INTEGER PRIMARY KEY AUTOINCREMENT');
  });

  test('the PostgreSQL DDL uses an identity column', () => {
    const sql = createTableSql(users, postgresDialect);
    expect(sql).toContain('CREATE TABLE IF NOT EXISTS "users"');
    expect(sql).toContain('"id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
    expect(sql).toContain('"email" TEXT NOT NULL UNIQUE');
  });

  test('the MySQL DDL uses backticks and InnoDB', () => {
    const sql = createTableSql(users, mysqlDialect);
    expect(sql).toContain('CREATE TABLE IF NOT EXISTS `users`');
    expect(sql).toContain('`email` VARCHAR(255) NOT NULL UNIQUE');
    expect(sql).toContain('ENGINE=InnoDB');
  });

  test('generateMigration emits the table and its indexes per dialect', () => {
    const withIndex = table('posts', [id(), text('title')], { indexes: [{ name: 'idx_title', columns: ['title'] }] });
    const migration = generateMigration({ tables: [withIndex], relations: [] }, 'initial', 'postgres');
    expect(migration.statements[0]).toContain('CREATE TABLE IF NOT EXISTS "posts"');
    expect(migration.statements[1]).toBe(
      'CREATE INDEX IF NOT EXISTS "idx_title" ON "posts" ("title")',
    );
  });

  test('the SQLite upsert names the conflict target', () => {
    const { sql, params } = sqliteDialect.upsert({
      table: 'users',
      values: { email: 'a@example.com', name: 'A' },
      conflictColumns: ['email'],
      update: { name: 'B' },
    });
    expect(sql).toBe(
      'INSERT INTO "users" ("email", "name") VALUES (?, ?) ON CONFLICT ("email") DO UPDATE SET "name" = ?',
    );
    expect(params).toEqual(['a@example.com', 'A', 'B']);
  });

  test('the MySQL upsert uses ON DUPLICATE KEY UPDATE', () => {
    const { sql, params } = mysqlDialect.upsert({
      table: 'users',
      values: { email: 'a@example.com', name: 'A' },
      conflictColumns: ['email'],
      update: { name: 'B' },
    });
    expect(sql).toBe(
      'INSERT INTO `users` (`email`, `name`) VALUES (?, ?) ON DUPLICATE KEY UPDATE `name` = ?',
    );
    expect(params).toEqual(['a@example.com', 'A', 'B']);
  });
});

describe('rendering', () => {
  test('portable placeholders become numbered ones on PostgreSQL', () => {
    const rendered = renderSql('SELECT * FROM t WHERE a = ? AND b = ?', [1, 2], postgresDialect);
    expect(rendered.sql).toBe('SELECT * FROM t WHERE a = $1 AND b = $2');
    expect(rendered.params).toEqual([1, 2]);
  });

  test('portable placeholders stay as they are on SQLite', () => {
    const rendered = renderSql('SELECT * FROM t WHERE a = ?', [1], sqliteDialect);
    expect(rendered.sql).toBe('SELECT * FROM t WHERE a = ?');
  });

  test('a question mark inside a literal is not a placeholder', () => {
    const rendered = renderSql("SELECT * FROM t WHERE a = 'x?y' AND b = ?", [1], postgresDialect);
    expect(rendered.sql).toBe("SELECT * FROM t WHERE a = 'x?y' AND b = $1");
  });

  test('a question mark inside a comment is not a placeholder', () => {
    const rendered = renderSql('SELECT * FROM t -- what?\n WHERE b = ?', [1], postgresDialect);
    expect(rendered.sql).toBe('SELECT * FROM t -- what?\n WHERE b = $1');
    const block = renderSql('SELECT * FROM t /* what? */ WHERE b = ?', [1], postgresDialect);
    expect(block.sql).toBe('SELECT * FROM t /* what? */ WHERE b = $1');
  });

  test('numbered placeholders are left alone', () => {
    const rendered = renderSql('SELECT * FROM t WHERE a = $1 AND b = $2', [1, 2], postgresDialect);
    expect(rendered.sql).toBe('SELECT * FROM t WHERE a = $1 AND b = $2');
  });

  test('mixing both placeholder styles is rejected', () => {
    expect(() => renderSql('SELECT * FROM t WHERE a = ? AND b = $1', [1, 2], postgresDialect)).toThrow(
      'mixes',
    );
  });

  test('a placeholder count that does not match the parameters is rejected', () => {
    expect(() => renderSql('SELECT * FROM t WHERE a = ?', [], postgresDialect)).toThrow(
      '1 placeholder(s) but 0 parameter(s)',
    );
  });

  test('the counters ignore quoted sections', () => {
    expect(countPlaceholders("SELECT '?', a FROM t WHERE b = ?")).toBe(1);
    expect(countPlaceholders('SELECT $1, $2 FROM t')).toBe(0);
    expect(countNumberedPlaceholders('SELECT $1, $2 FROM t')).toBe(2);
  });

  test('numberPlaceholders numbers the portable placeholders', () => {
    expect(numberPlaceholders('SELECT * FROM t WHERE a = ? AND b = ?')).toBe(
      'SELECT * FROM t WHERE a = $1 AND b = $2',
    );
  });
});

describe('drivers', () => {
  test('the adapter is inferred from the URL scheme', () => {
    expect(inferAdapter('postgres://localhost:5432/db')).toBe('postgres');
    expect(inferAdapter('mysql://localhost:3306/db')).toBe('mysql');
    expect(inferAdapter('mysql2://localhost:3306/db')).toBe('mysql');
    expect(inferAdapter('mariadb://localhost:3306/db')).toBe('mariadb');
  });

  test('a database reports the dialect of its driver', () => {
    const db = new Database(new SqliteDriver({ file: ':memory:' }));
    expect(db.dialect.name).toBe('sqlite');
    expect(db.dialectName).toBe('sqlite');
  });
});

describe('sqlite round trip', () => {
  async function makeDb(): Promise<Database> {
    const db = new Database(new SqliteDriver({ file: ':memory:' }));
    const migration = generateMigration({ tables: [users], relations: [] });
    for (const statement of migration.statements) {
      await db.executeRun(statement);
    }
    return db;
  }

  test('a boolean column comes back as a boolean', async () => {
    const db = await makeDb();
    const user = db.model({ name: 'user', table: users });
    const created = await user.create({
      data: { email: 'a@example.com', name: 'A', age: 30, active: true },
    });
    expect(created.active).toBe(true);

    const found = await user.findUnique({ where: { email: 'a@example.com' } });
    expect(found?.active).toBe(true);
    await db.close();
  });

  test('a boolean column is filtered by its boolean value', async () => {
    const db = await makeDb();
    const user = db.model({ name: 'user', table: users });
    await user.create({ data: { email: 'a@example.com', name: 'A', active: true } });
    await user.create({ data: { email: 'b@example.com', name: 'B', active: false } });

    const active = await user.findMany({ where: { active: true } });
    expect(active.length).toBe(1);
    expect(active[0].email).toBe('a@example.com');
    await db.close();
  });

  test('a column name keeps its case', async () => {
    const db = await makeDb();
    const rows = await db.query<{ email: string }>('SELECT "email" FROM "users"');
    expect(rows).toEqual([]);
    await db.close();
  });
});
